"""Produce the retrieval ablation table.

Runs every labelled answerable question through four retrieval configurations
and reports recall, precision, hit rate, and MRR for each. No LLM is involved,
so the table is deterministic: the same corpus and the same labels give the same
numbers on any machine.

    python -m tests.eval.run_ablation            # all answerable questions
    python -m tests.eval.run_ablation --limit 25 # a quick sample

Writes results to tests/eval/results/ablation.md.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

from dotenv import load_dotenv

RESULTS_DIR = Path(__file__).resolve().parent / "results"
TOP_K = 5


def main() -> None:
    load_dotenv()

    parser = argparse.ArgumentParser()
    parser.add_argument("--limit", type=int, default=0, help="score only the first N questions")
    parser.add_argument("--k", type=int, default=TOP_K)
    args = parser.parse_args()

    from app.ingest import build_embeddings
    from tests.eval.metrics import score_retrieval, summarize
    from tests.eval.retrievers import RETRIEVERS, naive_chunks, semantic_chunks
    from tests.eval.validate_dataset import load_dataset, validate

    records = load_dataset()
    problems = validate(records)
    if problems:
        raise SystemExit(
            f"dataset has {len(problems)} problem(s); fix them before measuring anything"
        )

    # Refusal cases have no anchors, so retrieval quality is undefined for them.
    answerable = [r for r in records if r["expected_behavior"] == "answer"]
    if args.limit:
        answerable = answerable[: args.limit]

    from tests.eval.conftest import eval_embed_model

    model = eval_embed_model()
    embeddings = build_embeddings(model)
    print(
        f"[ablation] model={model}, {len(answerable)} questions, k={args.k}, "
        f"{len(naive_chunks())} naive chunks, {len(semantic_chunks())} semantic chunks"
    )

    # Warm every question vector in one paced pass. Without this the first
    # retriever embeds 123 queries in a burst and trips the per-minute limit.
    from tests.eval.embedding_cache import embed_queries

    embed_queries([r["question"] for r in answerable], embeddings)

    summaries = {}
    per_question: dict[str, dict] = {}

    for name, retriever in RETRIEVERS.items():
        started = time.time()
        scores = []
        for record in answerable:
            texts = retriever(record["question"], args.k, embeddings)
            score = score_retrieval(record["id"], texts, record["source_anchors"])
            scores.append(score)
            per_question.setdefault(record["id"], {})[name] = {
                "recall": score.recall,
                "precision": score.precision,
                "first_hit_rank": score.first_hit_rank,
            }
        summaries[name] = summarize(scores)
        print(f"[ablation] {name:9s} done in {time.time() - started:.1f}s")

    header = (
        "| configuration | n | context recall | context precision | hit rate | MRR |\n"
        "|---|---|---|---|---|---|"
    )
    rows = [summaries[name].as_row(name) for name in RETRIEVERS]
    table = "\n".join([header, *rows])

    print()
    print(table)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (RESULTS_DIR / "ablation.md").write_text(
        "# Retrieval ablation\n\n"
        f"Generated by `python -m tests.eval.run_ablation` over {len(answerable)} "
        f"answerable labelled questions at k={args.k}.\n\n"
        "No LLM is involved. An anchor is either present in the retrieved text or it is\n"
        "not, so these numbers are deterministic and reproduce exactly on any machine\n"
        "with the same corpus and labels.\n\n"
        f"{table}\n\n"
        "**context recall** — fraction of a label's anchors appearing anywhere in the top k.\n\n"
        "**context precision** — fraction of retrieved chunks that carry an anchor. Falls as k\n"
        "grows past what a question needs, which is why it is read alongside recall.\n\n"
        "**hit rate** — questions where at least one anchor was retrieved.\n\n"
        "**MRR** — mean reciprocal rank of the first supporting chunk, counting a miss as 0.\n",
        encoding="utf-8",
    )
    (RESULTS_DIR / "ablation_per_question.json").write_text(
        json.dumps(per_question, indent=1), encoding="utf-8"
    )
    print(f"\n[ablation] wrote {RESULTS_DIR / 'ablation.md'}")


if __name__ == "__main__":
    main()
