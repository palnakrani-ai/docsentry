"""Latency, token, and cost report for the RAG pipeline.

Runs a sample of labelled questions through the real pipeline and reports p50
and p95 latency measured locally, plus token counts and cost pulled from
LangSmith when tracing is configured.

Latency is measured here rather than read from LangSmith because the number
that matters to a user is wall-clock time for the whole request, including the
retrieval and grounding work that happens outside any model call.

    python -m tests.eval.run_trace_report --limit 15

Writes tests/eval/results/trace_report.md.
"""

from __future__ import annotations

import argparse
import json
import os
import statistics
import time
from pathlib import Path

from dotenv import load_dotenv

RESULTS_DIR = Path(__file__).resolve().parent / "results"

# Published rates for gemini-flash-lite, USD per million tokens. Recorded here
# so the cost figure is reproducible and its basis is visible; if the rate card
# changes the number changes with it and the source is one line away.
USD_PER_MTOK_INPUT = 0.10
USD_PER_MTOK_OUTPUT = 0.40


def percentile(values: list[float], pct: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    rank = (pct / 100) * (len(ordered) - 1)
    low = int(rank)
    high = min(low + 1, len(ordered) - 1)
    return ordered[low] + (ordered[high] - ordered[low]) * (rank - low)


def fetch_langsmith_usage(project: str, since: float) -> dict | None:
    """Token totals for runs traced since `since`, or None if unavailable.

    Returns None rather than raising when LangSmith is not configured or not
    reachable. A tracing outage should not stop the latency report, which is
    the part measured locally and always available.
    """
    try:
        from langsmith import Client
    except ImportError:
        return None

    if not os.environ.get("LANGSMITH_API_KEY"):
        return None

    try:
        client = Client()
        import datetime

        start = datetime.datetime.fromtimestamp(since, tz=datetime.timezone.utc)
        runs = list(
            client.list_runs(
                project_name=project,
                start_time=start,
                is_root=True,
            )
        )
    except Exception as exc:  # noqa: BLE001 - tracing is best-effort
        print(f"[trace] LangSmith unavailable: {type(exc).__name__}: {exc}")
        return None

    prompt_tokens = sum((r.prompt_tokens or 0) for r in runs)
    completion_tokens = sum((r.completion_tokens or 0) for r in runs)

    return {
        "runs": len(runs),
        "prompt_tokens": prompt_tokens,
        "completion_tokens": completion_tokens,
        "total_tokens": prompt_tokens + completion_tokens,
    }


def main() -> None:
    load_dotenv()

    parser = argparse.ArgumentParser()
    parser.add_argument("--limit", type=int, default=15)
    args = parser.parse_args()

    from app.rag import answer_question
    from tests.eval.conftest import sample
    from tests.eval.validate_dataset import load_dataset

    records = sample(load_dataset())[: args.limit] or load_dataset()[: args.limit]
    project = os.environ.get("LANGSMITH_PROJECT", "default")
    tracing_on = os.environ.get("LANGSMITH_TRACING", "").lower() == "true"

    print(f"[trace] {len(records)} questions, tracing={'on' if tracing_on else 'off'}")

    started_at = time.time()
    latencies: list[float] = []
    refusals = 0

    for record in records:
        t0 = time.perf_counter()
        result = answer_question(record["question"])
        latencies.append((time.perf_counter() - t0) * 1000)
        refusals += 1 if result.refused else 0

    p50 = percentile(latencies, 50)
    p95 = percentile(latencies, 95)
    mean = statistics.fmean(latencies)

    usage = fetch_langsmith_usage(project, started_at) if tracing_on else None

    lines = [
        "# Latency, tokens, and cost",
        "",
        f"Generated by `python -m tests.eval.run_trace_report --limit {args.limit}` "
        f"over {len(records)} labelled questions.",
        "",
        "## Latency, measured locally",
        "",
        "Wall-clock time for the whole request, including retrieval and the grounding",
        "checks, not just the model call.",
        "",
        "| metric | ms |",
        "|---|---|",
        f"| p50 | {p50:.0f} |",
        f"| p95 | {p95:.0f} |",
        f"| mean | {mean:.0f} |",
        f"| min | {min(latencies):.0f} |",
        f"| max | {max(latencies):.0f} |",
        "",
        f"{refusals} of {len(records)} were refusals, which are faster because a refusal",
        "on an ungrounded retrieval short-circuits before the model is called.",
        "",
    ]

    if usage:
        total = usage["total_tokens"]
        cost = (
            usage["prompt_tokens"] / 1_000_000 * USD_PER_MTOK_INPUT
            + usage["completion_tokens"] / 1_000_000 * USD_PER_MTOK_OUTPUT
        )
        lines += [
            "## Tokens and cost, from LangSmith",
            "",
            f"| metric | value |",
            "|---|---|",
            f"| traced runs | {usage['runs']} |",
            f"| prompt tokens | {usage['prompt_tokens']:,} |",
            f"| completion tokens | {usage['completion_tokens']:,} |",
            f"| total tokens | {total:,} |",
            f"| mean tokens per request | {total / max(usage['runs'], 1):,.0f} |",
            f"| estimated cost | ${cost:.4f} |",
            f"| estimated cost per 1k requests | ${cost / max(usage['runs'], 1) * 1000:.2f} |",
            "",
            f"Costed at ${USD_PER_MTOK_INPUT}/Mtok input and ${USD_PER_MTOK_OUTPUT}/Mtok "
            "output for gemini-flash-lite. The rates are constants at the top of this",
            "script so the figure stays reproducible and its basis stays visible.",
            "",
        ]
    else:
        lines += [
            "## Tokens and cost",
            "",
            "Not collected. LangSmith tracing was disabled or unreachable for this run,",
            "so no token counts are reported rather than estimated ones being presented",
            "as measurements. Set LANGSMITH_TRACING=true and LANGSMITH_API_KEY to collect",
            "them.",
            "",
        ]

    report = "\n".join(lines)
    print()
    print(report)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (RESULTS_DIR / "trace_report.md").write_text(report, encoding="utf-8")
    (RESULTS_DIR / "trace_latencies.json").write_text(
        json.dumps(
            {
                "n": len(latencies),
                "p50_ms": p50,
                "p95_ms": p95,
                "mean_ms": mean,
                "refusals": refusals,
                "latencies_ms": [round(x, 1) for x in latencies],
                "langsmith": usage,
            },
            indent=1,
        ),
        encoding="utf-8",
    )
    print(f"\n[trace] wrote {RESULTS_DIR / 'trace_report.md'}")


if __name__ == "__main__":
    main()
